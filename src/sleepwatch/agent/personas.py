OTHER_CAUSES: list[tuple[str, str, Timing]] = [
    ("took a two-hour nap in the late afternoon", "nap", "afternoon"),
    ("started a new allergy medication that morning", "new medication", "morning"),
    ("had loud construction noise outside during the night", "noise", "during_night"),
    ("scrolled on my phone in bed until 1 am", "screen use in bed", "before_bed"),
    ("slept in a much hotter bedroom than usual", "hot room", "during_night"),
    ("was woken several times by my dog during the night", "disturbed by pet", "during_night"),
]
ORDINARY = [
    "worked from home as usual",
    "walked the dog in the morning",
    "had dinner at the usual time",
    "did some grocery shopping",
    "called my parents",
    "read a book for a bit",
    "took the bus to work",
    "tidied the flat",
]

STYLE_RULES = {
    "forthcoming": (
        "You are open and chatty. To the first question, mention most of the unusual things on "
        "your card. Answer follow-up questions fully."
    ),
    "reticent": (
        "You are private and brief, a few words per answer. Answer only what the question "
        "asks; don't volunteer anything else."
    ),
    "vague": (
        "You are vague and unsure about the unusual things on your card: hedge with 'I think', "
        "'maybe' or 'not sure', and don't remember exact times or amounts. Mention them when "
        "asked, loosely."
    ),
}

# Reticent people reveal hidden causes only when asked (decision 49): code shows the simulator
# one more cause per open question, and every cause whose topic a question names.
TOPICS = {
    "caffeine": r"caffein\w*|coffee\w*|tea|espresso\w*|energy drinks?|cola|drinks?|drinking",
    "alcohol": r"alcohol\w*|wine|beers?|cocktails?|spirits|drinks?|drinking",
    "late_exercise": r"exercis\w*|sports?|gym|workouts?|work out|run|running|training|"
    r"physical\w*|active",
    "late_meal": r"eat|eating|ate|meals?|food|dinner|supper|snack\w*",
    "stress": r"stress\w*|worr\w*|anxi\w*|tense|tension|upset|pressure|arguments?|mood",
    "illness": r"unwell|ill|illness|sick|pain\w*|ach\w*|health\w*|symptoms?|cold|fever\w*",
    "schedule_change": r"schedul\w*|bed ?time|to bed|routine|shifts?|travel\w*|time zones?|"
    r"slept in|sleep in|wake|woke|waking|later than usual|earlier than usual",
    "nap": r"naps?|napping|doz\w*",
    "new medication": r"medic\w*|pills?|tablets?|drugs?",
    "noise": r"nois\w*|loud|sounds?|disturb\w*",
    "screen use in bed": r"screens?|phones?|devices?|tv|television",
    "hot room": r"temperature\w*|hot|warm|room|bedroom|environment",
    "disturbed by pet": r"pets?|dogs?|cats?|disturb\w*|woke|wake|waking",
}
TOPIC_PATTERNS = {k: re.compile(rf"\b({v})\b", re.IGNORECASE) for k, v in TOPICS.items()}
OPEN_QUESTION = re.compile(
    r"\b(anything (else|different|unusual)|what else|something else|else (was|that)|"
    r"different|unusual|out of the ordinary)\b",
    re.IGNORECASE,
)


def unlocked(persona: Persona, turns: list[Turn]) -> list[int]:
    """Hidden causes a reticent person is willing to mention after these agent turns, in the
    order they were unlocked. A question that names topics unlocks the causes on those topics;
    one that names none but asks what else was different (and the templated opening) unlocks
    the next cause on the card."""
    shown: list[int] = []
    for t in turns:
        if t.role != "agent" or t.kind not in ("opening", "question", "fallback"):
            continue
        topics = (
            set()
            if t.kind == "opening"
            else {k for k, p in TOPIC_PATTERNS.items() if p.search(t.text)}
        )
        if topics:
            shown += [
                i
                for i, c in enumerate(persona.causes)
                if i not in shown and (c.kind or c.factor) in topics
            ]
        elif t.kind == "opening" or OPEN_QUESTION.search(t.text):
            shown += [i for i in range(len(persona.causes)) if i not in shown][:1]
    return shown


PERSONA_PROMPT = """\
You are role-playing a person in a test of a sleep app. The app's assistant will ask about \
your day before a night your watch recorded. Answer as this person, in plain first-person \
text like a message typed on a phone (1-3 sentences). Do not use lists or quotation marks.

{card}

How you talk: {style}

Rules:
- Only talk about what is on your card. Anything not on your card did not happen or was as \
usual: if asked about it, say so plainly, without hedging.
- The unusual things on your card did happen. Never say that one of them did not happen or was \
as usual, however a question puts it.
- When a question touches something on your card, even if you would call it something else, \
mention it.
- If you mention the ordinary things, make clear they were part of a normal day.
- Never add details of your own, such as drinks, meals, bedtimes, moods, symptoms or worries, \
even ordinary ones, and don't describe how you slept.
- Never guess why your sleep or heart rate was unusual, and never say that something caused or \
explains it, even if asked.
- Never mention your card, the test or that you are role-playing, and don't ask the assistant \
questions.
- If you have nothing more to add, say so."""

PERSONA_TOKENS = 200


class HiddenCause(BaseModel):
    model_config = ConfigDict(extra="forbid")

    factor: Factor
    detail: str  # first person, as the persona would say it
    timing: Timing
    certain: bool
    kind: str | None = None  # for "other": what it is


class Persona(BaseModel):
    model_config = ConfigDict(extra="forbid")

    persona_id: str
    style: Style
    causes: list[HiddenCause]
    ordinary: list[str]
    case_id: str
    seed: int

    def card(self, shown: list[int] | None = None) -> str:
        """The persona's card; ``shown`` limits it to those hidden causes (reticent people)."""
        causes = self.causes if shown is None else [self.causes[i] for i in shown]
        if causes:
            lines = [
                "Unusual things about that day, in your own words (share them as your way "
                "of talking allows):"
            ]
            for c in causes:
                sure = "" if c.certain else " (you are not sure about the details)"
                lines.append(f"- I {c.detail}.{sure}")
        elif self.causes:
            lines = ["Nothing unusual you want to mention right now."]
        else:
            lines = ["Nothing unusual happened that day. It was an ordinary day."]
        lines.append("Ordinary things you also did that day (not unusual):")
        lines += [f"- I {o}." for o in self.ordinary]
        return "\n".join(lines)


def make_personas(split: str, per_cell: int, seed: int, case_ids: list[str]) -> list[Persona]:
    """``per_cell`` personas for each style x number of causes, paired with cases in turn.

    Causes in a persona have distinct categories, with at most one "other". Pairing with cases
    is a seeded shuffle, independent of the causes."""
    rng = np.random.default_rng(seed)
    people = []
    for style in STYLES:
        for count in CAUSE_COUNTS:
            for rep in range(per_cell):
                causes: list[HiddenCause] = []
                categories = list(CHECKLIST)
                other_used = False
                for _ in range(count):
                    if not other_used and rng.random() < OTHER_SHARE:
                        detail, kind, timing = OTHER_CAUSES[rng.integers(len(OTHER_CAUSES))]
                        causes.append(
                            HiddenCause(
                                factor="other",
                                detail=detail,
                                timing=timing,
                                certain=style != "vague",
                                kind=kind,
                            )
                        )
                        other_used = True
                        continue
                    category = categories.pop(rng.integers(len(categories)))
                    detail, timing = CAUSES[category][rng.integers(len(CAUSES[category]))]
                    causes.append(
                        HiddenCause(
                            factor=category,
                            detail=detail,
                            timing=timing,
                            certain=style != "vague",
                        )
                    )
                ordinary = [ORDINARY[i] for i in rng.choice(len(ORDINARY), 2, replace=False)]
                people.append(
                    {
                        "persona_id": f"{split}-{style}-{count}-{rep}",
                        "style": style,
                        "causes": causes,
                        "ordinary": ordinary,
                        "seed": int(rng.integers(2**31)),
                    }
                )
    order = rng.permutation(len(people))
    return [Persona(**people[i], case_id=case_ids[k % len(case_ids)]) for k, i in enumerate(order)]


class SimulatedUser:
    """An LLM playing a persona: the agent's turns are its "user" messages."""

    def __init__(self, persona: Persona, backend: ChatBackend, temperature: float = 0.7) -> None:
        self.persona = persona
        self.backend = backend
        self.temperature = temperature

    def messages(self, turns: list[Turn]) -> Messages:
        shown = unlocked(self.persona, turns) if self.persona.style == "reticent" else None
        system = PERSONA_PROMPT.format(
            card=self.persona.card(shown), style=STYLE_RULES[self.persona.style]
        )
        out = [{"role": "system", "content": system}]
        for t in turns:
            out.append({"role": "user" if t.role == "agent" else "assistant", "content": t.text})
        return out

    def __call__(self, turns: list[Turn]) -> str:
        reply = self.backend.chat(
            self.messages(turns),
            temperature=self.temperature,
            seed=self.persona.seed,
            max_tokens=PERSONA_TOKENS,
        )
        return reply.text.strip()
